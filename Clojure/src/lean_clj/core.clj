(ns lean-clj.core
  "Embed Lean in Clojure.

  `deflean` takes Lean source, checks it (including every proof) with `lake
  build` at macro-expansion time, and defines the Lean functions in the current
  namespace through code generated by the `lean-clj` CLI."
  (:require
    [clojure.java.io :as io]
    [clojure.java.shell :as sh]
    [clojure.string :as str]
    [lean-clj.dsl :as dsl]
    [lean-clj.runtime])
  (:import
    (java.io
      File
      PushbackReader
      StringReader)
    (java.security
      MessageDigest)))


(set! *warn-on-reflection* true)


(def generator-version
  "Part of the cache key, so that cached output is regenerated when the
  generator changes."
  "0.1.1")


(def ^:dynamic *workspace*
  "Directory of the lake workspace and the generated-code cache."
  (io/file ".lean-clj"))


(defn- camel
  [s]
  (->> (str/split (str s) #"[-_]")
       (remove str/blank?)
       (map str/capitalize)
       (apply str)))


(defn module-name
  "Lean module of the block `block` in the Clojure namespace `ns-name`."
  [ns-name block]
  (str/join "." (concat ["LeanCljEmbed"]
                        (map camel (str/split (str ns-name) #"\."))
                        [(camel block)])))


(defn- dedent
  [^String src]
  (let [[head & tail] (str/split-lines src)
        indents (->> tail
                     (remove str/blank?)
                     (map #(count (re-find #"^ *" %))))
        n (if (seq indents) (apply min indents) 0)]
    (str/join "\n" (cons head (map #(if (str/blank? %) "" (subs % (min n (count %)))) tail)))))


(defn- sha256
  [^String s]
  (let [d (.digest (MessageDigest/getInstance "SHA-256") (.getBytes s "UTF-8"))]
    (apply str (map #(format "%02x" (bit-and (long %) 0xff)) d))))


(defn- find-exe
  [name]
  (or (some (fn [dir]
              (let [f (io/file dir name)]
                (when (and (.isFile f) (.canExecute f)) (.getAbsolutePath f))))
            (str/split (or (System/getenv "PATH") "") (re-pattern File/pathSeparator)))
      (throw (ex-info (str "lean-clj: `" name "` was not found on PATH") {:executable name}))))


(defn- sh!
  [dir & args]
  (apply sh/sh (concat args [:dir (str dir)])))


(def ^:private lakefile
  "name = \"lean-clj-embed\"\n\n[[lean_lib]]\nname = \"LeanCljEmbed\"\nglobs = [\"LeanCljEmbed.+\"]\n")


(defn- ensure-workspace!
  ^File []
  (let [ws (io/file *workspace*)
        lf (io/file ws "lakefile.toml")]
    (.mkdirs ws)
    (when-not (and (.exists lf) (= lakefile (slurp lf)))
      (spit lf lakefile))
    ws))


(defn- lean-file
  [module {:keys [imports]} src]
  (let [header (str (str/join (map #(str "import " % "\n") imports))
                    "namespace " module "\n\n")]
    {:text (str header src "\n\nend " module "\n")
     :offset (count (filter #{\newline} header))}))


(defn- relocate-messages
  "Rewrite `<file>:<line>:<col>` in Lean's output to lines of the block."
  [out ^String path offset block]
  (-> out
      (str/replace #"(?m)^(✖|trace:|Some required targets|- LeanCljEmbed|error: build failed).*\n?" "")
      (str/replace (re-pattern (str (java.util.regex.Pattern/quote path) ":(\\d+):(\\d+)"))
                   (fn [[_ line col]]
                     (str "deflean " block ":" (- (parse-long line) offset) ":" col)))))


(defn- numbered
  [src]
  (->> (str/split-lines src)
       (map-indexed (fn [i l] (format "%4d | %s" (inc i) l)))
       (str/join "\n")))


(defn- generate!
  [ns-name block opts src]
  (let [ws (ensure-workspace!)
        module (module-name ns-name block)
        rel (str (str/replace module "." "/") ".lean")
        {:keys [text offset]} (lean-file module opts src)
        f (io/file ws rel)
        out (io/file ws "out" (str (sha256 text) ".clj"))]
    (io/make-parents f)
    (spit f text)
    (let [{:keys [exit] :as r} (sh! ws (find-exe "lake") "build" module)]
      (when-not (zero? exit)
        (throw (ex-info (str "lean-clj: Lean rejected deflean " block "\n"
                             (relocate-messages (str (:out r) (:err r)) rel offset block)
                             "\nLean source of the block:\n" (numbered src))
                        {:block block :module module :exit exit}))))
    (let [{:keys [exit err]} (sh! ws (find-exe "lean-clj")
                                  "module" "generate-namespace"
                                  "--module-name" module
                                  "--namespace" (str ns-name)
                                  "--search-path" (.getAbsolutePath (io/file ws ".lake" "build" "lib" "lean"))
                                  "--forms-only"
                                  "--output-file" (.getAbsolutePath out))]
      (when-not (zero? exit)
        (throw (ex-info (str "lean-clj: code generation failed for deflean " block "\n" err)
                        {:block block :module module :exit exit}))))
    (slurp out)))


(defn- read-forms
  [^String text]
  (binding [*read-eval* false]
    (let [r (PushbackReader. (StringReader. text))]
      (loop [acc []]
        (let [form (read {:eof ::eof} r)]
          (if (= form ::eof) acc (recur (conj acc form))))))))


(defn expand
  "Clojure forms for the deflean block `block` in `ns-name`, given its Lean
  source. Generated code is cached in `*workspace*`/cache under a hash of the
  inputs."
  [ns-name block opts src]
  (let [key (sha256 (pr-str [generator-version (str ns-name) (str block) (:imports opts) src]))
        cached (io/file *workspace* "cache" (str key ".clj"))
        text (if (.exists cached)
               (slurp cached)
               (let [t (generate! ns-name block opts src)]
                 (io/make-parents cached)
                 (spit cached t)
                 t))]
    (read-forms text)))


(defn source
  "Lean source of a deflean body: strings are Lean source (dedented), other
  forms are commands of `lean-clj.dsl`."
  [body]
  (->> body
       (map #(if (string? %) (dedent %) (dsl/command %)))
       (str/join "\n\n")))


(defmacro deflean
  "Define the functions of a block of Lean in the current namespace.

    (deflean arith
      (def double [n Nat] Nat
        (+ n n))

      (theorem double_eq [n Nat] (= (double n) (* 2 n))
        (by (unfold double) omega)))

  The body is a sequence of `lean-clj.dsl` commands; a string in the body is
  Lean source taken as is. An optional map before the body takes `:imports`,
  a vector of Lean modules to import. The block becomes the Lean module
  returned by `module-name`, whose definitions are wrapped in a namespace of
  the same name. Lean checks the whole block, proofs included, when the macro
  expands; a rejected block stops compilation with Lean's messages."
  [block & args]
  (let [[opts body] (if (map? (first args)) [(first args) (rest args)] [{} args])]
    `(do ~@(expand (ns-name *ns*) block opts (source body)))))
