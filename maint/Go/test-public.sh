#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../../langs/Go"

lake build leanfran-go oracle-public +LeanGoTest.PublicClient
out=test-out/_generated/public
mkdir -p "$out"
compiler=.lake/build/bin/leanfran-go
search=.lake/build/lib/lean

generate() {
    local mod=$1
    local path=$2
    shift 2
    "$compiler" module generate --module-name "LeanGoTest.$mod"         --search-path "$search" --output-dir "$path" "$@"
}

generate Public "$out/public" > "$out/public.summary.json"
generate Json "$out/json" > "$out/json.summary.json"
generate PublicClient "$out/client" --package client     --type-module LeanGoTest.Public=github.com/conao3/leanfran-go/test-out/_generated/public/public     > "$out/client.summary.json"

mkdir -p "$out/repeat"
printf '// Code generated by leanfran-go (old)\npackage public\n' > "$out/repeat/stale.go"
printf 'package public\n' > "$out/repeat/user.go"
generate Public "$out/repeat" > "$out/repeat.summary.json"
test ! -e "$out/repeat/stale.go"
test -f "$out/repeat/user.go"
for file in "$out/public/"*_gen.go; do
    cmp "$file" "$out/repeat/${file##*/}"
done
test -z "$(gofmt -l "$out/public" "$out/json" "$out/client")"

python3 - "$out" <<'PY'
import json
import sys
from pathlib import Path

directory = Path(sys.argv[1])
summary = json.loads((directory / "public.summary.json").read_text())
assert summary["package"] == "public"
assert len(summary["files"]) == 3
skipped = {row["name"].rsplit(".", 1)[-1]: row["reason"] for row in summary["skipped"]}
for name, reason in {
    "AClass": "type class",
    "AProp": "proposition",
    "Generic": "polymorphic",
    "HasType": "type field",
    "Indexed": "indexed",
    "NoDecider": "Decidable",
    "secret": "private",
    "ioRefEcho": "unsupported",
    "leanEcho": "unsupported",
    "stdEcho": "unsupported",
    "systemEcho": "unsupported",
    "taskEcho": "unsupported",
    "thunkEcho": "unsupported",
}.items():
    assert reason in skipped.get(name, ""), (name, reason, skipped)
PY

cp testdata/public/public_test.go "$out/public"
cp testdata/public/oracle.go "$out"
go vet "./$out/public" "./$out/json" "./$out/client" "./$out"
go test -race "./$out/public"
CGO_ENABLED=0 go build -o "$out/oracle" "./$out"
.lake/build/bin/oracle-public > "$out/native.jsonl"
"$out/oracle" > "$out/emitted.jsonl"
diff -u "$out/native.jsonl" "$out/emitted.jsonl"
"$out/oracle" schema > "$out/go-schema.json"

typescript=$(nix build ../..#typescript --no-link --print-out-paths)
nix develop ../..#typescript -c bash -s -- "$typescript/bin/leanfran-typescript" "$out" "$search" <<'TYPESCRIPT'
set -euo pipefail
compiler=$1
out=$2
search=$3
"$compiler" module generate --module-name LeanGoTest.Public --namespace LeanGoTest.Public     --roots LeanGoTest.Public.total LeanGoTest.Public.packedEcho LeanGoTest.Public.rangeEcho     --search-path "$search" --runtime-path ../../../../TypeScript/src/runtime/index.ts     --output-file "$out/Public.ts" > "$out/typescript-public.summary.json"
"$compiler" module generate --module-name LeanGoTest.Json --namespace LeanGoTest.Json     --roots LeanGoTest.Json.{big,bigEcho,data,shapes,colors,trees}     --search-path "$search" --runtime-path ../../../../TypeScript/src/runtime/index.ts     --output-file "$out/Json.ts" > "$out/typescript-json.summary.json"
cp ../../maint/Go/schema-oracle.mjs "$out"
node "$out/schema-oracle.mjs" > "$out/typescript-schema.json"
TYPESCRIPT

python3 - "$out" <<'PY'
import difflib
import json
import sys
from pathlib import Path

directory = Path(sys.argv[1])
go = json.loads((directory / "go-schema.json").read_text())
ts = json.loads((directory / "typescript-schema.json").read_text())
if go != ts:
    left = json.dumps(ts, sort_keys=True, indent=2).splitlines()
    right = json.dumps(go, sort_keys=True, indent=2).splitlines()
    sys.exit("\n".join(difflib.unified_diff(left, right, "TypeScript", "Go", lineterm="")))
print(f"Matched {len(go)} JSON Schemas and {len((directory / 'native.jsonl').read_text().splitlines())} native results")
PY
