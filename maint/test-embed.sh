#!/usr/bin/env bash
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
lake --dir "$root" build leanfran-embed-test >/dev/null
driver="$root/.lake/build/bin/leanfran-embed-test"
work=$(mktemp -d)
trap 'chmod -R u+w "$work"; rm -rf "$work"' EXIT
export LEANFRAN_FAKE_PACKAGE="$root/tests/embed/fake.sh"
export LEANFRAN_FAKE_LOG="$work/scan.log"
project="$work/project"
mkdir -p "$project/fake" "$project/old" "$project/lean/Proofs"
cd "$project"

fail() {
    printf 'test-embed.sh: %s\n' "$*" >&2
    exit 1
}

expect() {
    local expected=$1 status=0
    shift
    "$driver" "$@" >"$work/out" 2>"$work/err" || status=$?
    if [[ $status != "$expected" ]]; then
        cat "$work/out" "$work/err" >&2
        fail "$*: expected status $expected, found $status"
    fi
}

contains() {
    grep -Fq -- "$2" "$work/$1" || { cat "$work/out" "$work/err" >&2; fail "$1 does not contain: $2"; }
}

write_scan() {
    local alpha_hash=$1 files=$2 extra_blocks=${3:-} functions=${4:-}
    cat >fake/scan.json <<JSON
{"format": 1, "scope": ["."], "require": [], "inputs": "",
 "blocks": [
  {"name": "alpha", "module": "FakeBlocks.Alpha", "path": "FakeBlocks/Alpha.lean", "prelude": "",
   "text": "def alpha : Nat := 1\n", "postlude": "", "map": [[0, 3, 1]],
   "origin": {"file": "src/alpha.fake", "line": 2, "column": 1}, "uses": [], "hash": "$alpha_hash",
   "job": {"module": "FakeBlocks.Alpha", "files": {"alpha.txt": "// generated by fake\nalpha\n"}},
   "output": {"dir": "gen"}},
  {"name": "beta", "module": "FakeBlocks.Beta", "path": "FakeBlocks/Beta.lean", "prelude": "import FakeBlocks.Alpha\n",
   "text": "def beta : Nat := alpha + 1\n", "postlude": "", "map": [[0, 7, 1]],
   "origin": {"file": "src/beta.fake", "line": 6, "column": 1}, "uses": ["alpha"], "hash": "b1",
   "job": {"module": "FakeBlocks.Beta", "files": {"beta.txt": "// generated by fake\nbeta\n"}},
   "output": {"file": "gen/beta.txt"}}$extra_blocks
 ],
 "workspace": [], "files": [$files], "stray": ["old/stray.txt"],
 "functions": [$functions], "proof_inputs": "p1"}
JSON
}

alias='{"path": "gen/alias.txt", "text": "// generated by fake\nalias\n", "block": "beta"}'
printf '// generated by fake\nold\n' >old/stray.txt
write_scan a1 "$alias"
expect 1 --lang fake-byte status
contains out 'alpha: stale'
contains out 'old/stray.txt: removed'
test ! -e .leanfran || fail 'status created .leanfran'

expect 0 --lang fake-byte sync
contains err 'leanfran: 2 blocks checked and generated'
contains err 'leanfran: removed old/stray.txt'
for file in gen/alpha.txt gen/beta.txt gen/alias.txt fake_extra.txt; do
    test -f "$file" || fail "$file was not placed"
done
test ! -e old || fail 'the directory of the removed stray file is left'
grep -Fxq '/lock' .leanfran/.gitignore && grep -Fxq '/fake-byte/' .leanfran/.gitignore ||
    fail '.leanfran/.gitignore lacks /lock or /fake-byte/'
test -f .leanfran/fake-byte/workspace/FakeBlocks/Beta.lean || fail 'the workspace has no block module'
grep -Fq '"files": ["gen/alias.txt", "gen/beta.txt"]' leanfran.manifest.json || fail 'manifest files of beta'
expect 0 --lang fake-byte status
test ! -s "$work/out" || fail 'status printed rows for fresh blocks'

write_scan a2 "$alias"
expect 1 --lang fake-byte status
contains out 'alpha: stale'
expect 0 --lang fake-byte sync

printf 'mine\n' >gen/owned.txt
write_scan a2 "$alias, {\"path\": \"gen/owned.txt\", \"text\": \"// generated by fake\nowned\n\"}"
expect 254 --lang fake-byte sync
contains err 'refusing to overwrite gen/owned.txt, which leanfran did not generate'
test "$(cat gen/owned.txt)" = mine || fail 'the user file was overwritten'
rm gen/owned.txt

cp leanfran.manifest.json "$work/manifest.json"
cp gen/alias.txt "$work/alias.txt"
mkdir -p locked
chmod a-w locked
write_scan a2 '{"path": "gen/alias.txt", "text": "// generated by fake\nchanged\n", "block": "beta"}, {"path": "locked/x.txt", "text": "x\n"}'
expect 255 --lang fake-byte sync
contains err 'could not install the generated files'
chmod u+w locked
rmdir locked
cmp gen/alias.txt "$work/alias.txt" || fail 'gen/alias.txt was not restored'
cmp leanfran.manifest.json "$work/manifest.json" || fail 'the manifest changed after a failed sync'
if ls -a gen | grep -q '^\.leanfran-'; then fail 'temporary files are left in gen'; fi

gamma=', {"name": "gamma", "module": "FakeBlocks.Gamma", "path": "FakeBlocks/Gamma.lean", "prelude": "",
   "text": "def gamma : String := \"é𝔸\" ++ missing\n", "postlude": "", "map": [[0, 10, 5]],
   "origin": {"file": "src/gamma.fake", "line": 9, "column": 1}, "uses": [], "hash": "g1",
   "job": {"module": "FakeBlocks.Gamma"}, "output": {"dir": "gen"}}'
write_scan a2 "$alias" "$gamma"
expect 254 --lang fake-byte sync
contains err 'src/gamma.fake:10:39: error: (lean block gamma, Lean 1:30)'
expect 254 --lang fake-utf16 sync
contains err 'src/gamma.fake:10:36: error: (lean block gamma, Lean 1:30)'
cmp leanfran.manifest.json "$work/manifest.json" || fail 'the manifest changed after a Lean error'

failing=', {"name": "delta", "module": "FakeBlocks.Delta", "path": "FakeBlocks/Delta.lean", "prelude": "",
   "text": "def delta : Nat := 4\n", "postlude": "", "map": [[0, 1, 1]],
   "origin": {"file": "src/delta.fake", "line": 1, "column": 1}, "uses": [], "hash": "d1",
   "job": {"module": "FakeBlocks.Delta", "fail": "cannot generate delta"}, "output": {"dir": "gen"}}'
write_scan a2 "$alias" "$failing"
expect 254 --lang fake-byte sync
contains err 'delta: cannot generate delta'

printf '254\n' >fake/scan.exit
printf 'src/alpha.fake:2:3: broken block\n' >fake/scan.err
expect 254 --lang fake-byte sync
contains err 'src/alpha.fake:2:3: broken block'
printf '3\n' >fake/scan.exit
expect 255 --lang fake-byte status
contains err 'exited with 3'
rm fake/scan.exit fake/scan.err
LEANFRAN_FAKE_GENERATOR_VERSION=2 expect 255 --lang fake-byte status
contains err 'compiler generator version "1", expected 2'
write_scan a2 "$alias"
printf 'not json' >"$work/scan.json"
mv fake/scan.json "$work/scan.good"
cp "$work/scan.json" fake/scan.json
expect 255 --lang fake-byte status
contains err 'printed output that leanfran cannot read'
mv "$work/scan.good" fake/scan.json
expect 252 --lang fake-byte sync --require proved
expect 252 --lang fake-byte status --dir

touch fake/slow
: >"$LEANFRAN_FAKE_LOG"
"$driver" --lang fake-byte sync >/dev/null 2>"$work/first" &
first=$!
sleep 1
"$driver" --lang fake-byte sync >/dev/null 2>"$work/second"
wait "$first"
rm fake/slow
mapfile -t log <"$LEANFRAN_FAKE_LOG"
[[ ${#log[@]} == 4 && ${log[0]} == start* && ${log[1]} == end* && ${log[2]} == start* && ${log[3]} == end* &&
    ${log[0]#start } == "${log[1]#end }" ]] || fail "the two syncs overlapped: ${log[*]}"

double='{"id": "fake.double", "labels": ["refines"], "hash": "h1", "origin": {"file": "src/alpha.fake", "line": 4, "column": 1}}'
bad='{"id": "fake.bad", "labels": ["refines"], "hash": "h2", "origin": {"file": "src/alpha.fake", "line": 8, "column": 1}}'
write_scan a2 "$alias" '' "$double, $bad"
cat >fake/translate.json <<'JSON'
{"format": 1,
 "modules": [{"module": "FakeModel.Double", "path": "FakeModel/Double.lean",
   "text": "import FakeBlocks.Alpha\n\ndef FakeModel.double (n : Nat) : Nat := n + n + alpha\n", "functions": ["fake.double"]}],
 "aggregates": [{"module": "FakeModel.All", "path": "FakeModel/All.lean", "text": "import FakeModel.Double\n"}],
 "functions": [{"id": "fake.double", "model": "FakeModel.double", "dependencies": []},
   {"id": "fake.bad", "model": "FakeModel.bad", "error": {"file": "src/alpha.fake", "line": 8, "column": 3, "message": "unsupported"}}]}
JSON
printf 'import FakeModel.All\n\ntheorem double_refines : True := trivial\n' >lean/Proofs/Double.lean
LEANFRAN_FAKE_INPUT="$work/translate-input.json" expect 1 --lang fake-byte check
contains out 'fake.double [refines]: proved'
contains out 'fake.bad [refines]: unextracted'
contains err 'src/alpha.fake:8:3: unextracted fake.bad: unsupported'
grep -Fq '"workspace":' "$work/translate-input.json" || fail 'translate did not receive its input'
grep -Fq '"format": "leanfran-lock"' leanfran.lock || fail 'the lock has another format'
expect 0 --lang fake-byte status
contains out 'fake.double [refines]: proved'
expect 1 --lang fake-byte status --require proved
printf '\n-- edited\n' >>lean/Proofs/Double.lean
expect 1 --lang fake-byte status
contains out 'fake.double [refines]: stale'

printf '[package]\nname = "app"\n' >leanfran.lock
expect 254 --lang fake-byte status
contains err 'leanfran.lock is not a lock of leanfran --lang fake-byte'
printf '{"version": 1, "inputs": "x", "functions": {}, "obligations": []}\n' >leanfran.lock
expect 1 --lang fake-byte status
contains out 'fake.double [refines]: stale'

echo "test-embed.sh: placement, rollback, ownership, stray removal, locking, position maps, host commands, batch errors and the lock passed"
