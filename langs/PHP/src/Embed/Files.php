<?php

declare(strict_types=1);

namespace Conao3\Leanfran\Embed;

use Generator;
use RuntimeException;

/** File operations shared by the embedding commands. */
final class Files
{
    /** Reads a file or reports its path. */
    public static function read(string $path): string
    {
        $text = @file_get_contents($path);
        if ($text === false) {
            throw new RuntimeException("cannot read $path");
        }
        return $text;
    }

    /** Parses a JSON file. */
    public static function json(string $path): mixed
    {
        try {
            return json_decode(self::read($path), flags: JSON_THROW_ON_ERROR);
        } catch (\JsonException $error) {
            throw new RuntimeException("$path: {$error->getMessage()}", previous: $error);
        }
    }

    /**
     * Returns the paths of a directory's immediate children in sorted order.
     *
     * @return list<string>
     */
    public static function entries(string $dir): array
    {
        $names = @scandir($dir);
        if ($names === false) {
            throw new RuntimeException("cannot list $dir");
        }
        $paths = [];
        foreach ($names as $name) {
            if ($name !== '.' && $name !== '..') {
                $paths[] = "$dir/$name";
            }
        }
        return $paths;
    }

    /**
     * Finds files within project directories without following links.
     *
     * @return Generator<int, string>
     */
    public static function walk(string $dir, bool $stopAtPackages = false): Generator
    {
        foreach (self::entries($dir) as $path) {
            if (is_link($path)) {
                continue;
            }
            if (is_file($path)) {
                yield $path;
            } elseif (
                is_dir($path)
                && !in_array(basename($path), ['vendor', '.git', '.leanfran'], true)
                && (!$stopAtPackages || !is_file("$path/composer.json"))
            ) {
                yield from self::walk($path, $stopAtPackages);
            }
        }
    }

    /** Tests whether a PHP file carries the generator's ownership marker. */
    public static function generated(string $file): bool
    {
        return self::generatedHeader($file) !== null;
    }

    /** Reads the generator's first-line marker. */
    public static function generatedHeader(string $file): ?string
    {
        if (!str_ends_with($file, '.php') || is_link($file) || !is_file($file)) {
            return null;
        }
        $handle = @fopen($file, 'rb');
        if ($handle === false) {
            throw new RuntimeException("cannot read $file");
        }
        try {
            $line = fgets($handle);
            return $line !== false && str_starts_with($line, '<?php // Generated by leanfran-php ') ? $line : null;
        } finally {
            fclose($handle);
        }
    }
}
