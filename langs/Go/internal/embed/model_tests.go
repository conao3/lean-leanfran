package embed

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/conao3/leanfran-go/internal/verify"
)

const modelTestHeader = "// Code generated by leanfran-go model tests. DO NOT EDIT.\n"

func (p *project) testModels(models []*verify.Function) map[string][]*verify.Function {
	pkgs := make(map[string][]*verify.Function)
	for _, m := range models {
		if m.Err == nil && p.blocks[m.Spec] != nil {
			pkgs[m.Package] = append(pkgs[m.Package], m)
		}
	}
	return pkgs
}

func (p *project) modelTests(models []*verify.Function) ([]change, error) {
	pkgs := p.testModels(models)
	var changes []change
	for _, dir := range p.dirs {
		path, err := p.packagePath(dir)
		if err != nil {
			return nil, err
		}
		filename := filepath.Join(dir, verify.TestFile)
		if len(pkgs[path]) == 0 {
			if data, err := readRegular(filename); err == nil && bytes.HasPrefix(data, []byte(modelTestHeader)) {
				changes = append(changes, change{path: filename})
			}
			continue
		}
		source, err := p.testSource(p.packages[path].name, pkgs[path])
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filename, err)
		}
		changes = append(changes, change{path: filename, data: source})
	}
	return changes, nil
}

func (p *project) testStatus(models []*verify.Function, out io.Writer) error {
	pkgs := p.testModels(models)
	var bad bool
	for _, dir := range p.dirs {
		path, err := p.packagePath(dir)
		if err != nil {
			return err
		}
		file := filepath.Join(dir, verify.TestFile)
		data, err := readRegular(file)
		exists := err == nil && bytes.HasPrefix(data, []byte(modelTestHeader))
		if exists != (len(pkgs[path]) != 0) {
			bad = true
			if _, err := fmt.Fprintf(out, "%s: stale or missing %s\n", path, verify.TestFile); err != nil {
				return err
			}
		}
	}
	if bad {
		return fmt.Errorf("generated model tests are out of date")
	}
	return nil
}

func (p *project) testSource(pkg string, models []*verify.Function) ([]byte, error) {
	imports := make(map[string]string)
	var cases strings.Builder
	testerNeeded := false
	for _, m := range models {
		block := p.blocks[m.Spec]
		model := m.Decl.Name.Name
		names := make([]string, 0, 1+len(m.Checks))
		if m.Needs != "" {
			names = append(names, m.Needs)
		}
		for _, pred := range m.Checks {
			names = append(names, pred.Name)
		}
		var missing string
		for _, n := range names {
			if block.wrappers[n] == "" {
				missing = n
				break
			}
		}
		fmt.Fprintf(&cases, "\tt.Run(%s, func(t *testing.T) {\n", strconv.Quote(model))
		switch {
		case missing != "":
			fmt.Fprintf(&cases, "\t\tt.Fatal(%s)\n", strconv.Quote("no generated Go function for Lean spec "+m.Spec+":"+missing))
		case block.pkg.name == "main" && m.Package != m.Spec:
			fmt.Fprintf(&cases, "\t\tt.Fatal(%s)\n", strconv.Quote("cannot import spec from command package "+m.Spec))
		default:
			testerNeeded = true
			prefix := ""
			if m.Package != m.Spec {
				alias := imports[m.Spec]
				if alias == "" {
					alias = fmt.Sprintf("spec%d", len(imports))
					imports[m.Spec] = alias
				}
				prefix = alias + "."
			}
			fmt.Fprintf(&cases, "\t\tleanfrantest.Check(t, leanfrantest.Model{Name: %s, Function: %s,\n", strconv.Quote(model), model)
			if m.Needs != "" {
				fmt.Fprintf(&cases, "\t\t\tRequires: %s%s,\n", prefix, block.wrappers[m.Needs])
			}
			hasEnsures := false
			for _, pred := range m.Checks {
				if pred.Label == "refines" {
					fmt.Fprintf(&cases, "\t\t\tRefines: %s%s,\n", prefix, block.wrappers[pred.Name])
				} else {
					hasEnsures = true
				}
			}
			if hasEnsures {
				fmt.Fprintln(&cases, "\t\t\tEnsures: map[string]any{")
				for _, pred := range m.Checks {
					if pred.Label != "refines" {
						fmt.Fprintf(&cases, "\t\t\t\t%q: %s%s,\n", pred.Label, prefix, block.wrappers[pred.Name])
					}
				}
				fmt.Fprintln(&cases, "\t\t\t},")
			}
			fmt.Fprintln(&cases, "\t\t})")
		}
		fmt.Fprintln(&cases, "\t})")
	}
	var source strings.Builder
	fmt.Fprintf(&source, "%s\npackage %s\n\nimport (\n\t\"testing\"\n", modelTestHeader, pkg)
	if testerNeeded {
		fmt.Fprintf(&source, "\t%q\n", runtimePath+"/leanfrantest")
	}
	for _, path := range sortedKeys(imports) {
		fmt.Fprintf(&source, "\t%s %q\n", imports[path], path)
	}
	fmt.Fprintf(&source, ")\n\nfunc TestLeanfranModels(t *testing.T) {\n%s}\n", cases.String())
	return format.Source([]byte(source.String()))
}
