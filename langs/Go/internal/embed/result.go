var generatedNames = []string{"leanfran_types_gen.go", "leanfran_funcs_gen.go", "leanfran_lean_gen.go"}

var embeddedHeader = regexp.MustCompile(`^// Code generated by leanfran-go \(generator [^\r\n]+\) from LeanGoEmbed\.B[0-9a-f]+\. DO NOT EDIT\.`)

var located = regexp.MustCompile(`(?s)^(.+?):([0-9]+):([0-9]+): (.*)$`)

const modelTestHeader = "// Code generated by leanfran-go model tests. DO NOT EDIT.\n"

type Versions struct {
	Release, Generator, Lean string
}

type Origin struct {
	File   string `json:"file"`
	Line   int    `json:"line"`
	Column int    `json:"column"`
}

type SourceError struct {
	File    string `json:"file"`
	Line    int    `json:"line"`
	Column  int    `json:"column"`
	Message string `json:"message"`
}

type batchJob struct {
	Module      string   `json:"module"`
	Package     string   `json:"package"`
	GoPath      string   `json:"go_path"`
	TypeModules []string `json:"type_modules,omitempty"`
	Models      []*model `json:"models,omitempty"`
}

type Block struct {
	Name     string            `json:"name"`
	Module   string            `json:"module"`
	Path     string            `json:"path"`
	Prelude  string            `json:"prelude"`
	Text     string            `json:"text"`
	Postlude string            `json:"postlude"`
	Map      [][3]int          `json:"map"`
	Origin   Origin            `json:"origin"`
	Uses     []string          `json:"uses"`
	Hash     string            `json:"hash"`
	Job      batchJob          `json:"job"`
	Output   map[string]string `json:"output"`
}

type WorkspaceFile struct {
	Path string `json:"path"`
	Text string `json:"text"`
}

type FunctionData struct {
	Dir      string      `json:"dir"`
	Package  string      `json:"package"`
	Function string      `json:"function"`
	Spec     string      `json:"spec"`
	Requires string      `json:"requires,omitempty"`
	Checks   [][2]string `json:"checks"`
	Error    string      `json:"error,omitempty"`
}

type Function struct {
	ID     string       `json:"id"`
	Labels []string     `json:"labels"`
	Hash   string       `json:"hash"`
	Origin Origin       `json:"origin"`
	Data   FunctionData `json:"data"`
}

type ScanResult struct {
	Format      int              `json:"format"`
	Scope       []string         `json:"scope"`
	Require     []map[string]any `json:"require"`
	Inputs      string           `json:"inputs"`
	Blocks      []Block          `json:"blocks"`
	Workspace   []WorkspaceFile  `json:"workspace"`
	Files       []WorkspaceFile  `json:"files"`
	Stray       []string         `json:"stray"`
	Functions   []Function       `json:"functions"`
	ProofInputs string           `json:"proof_inputs"`
}

type TranslateInput struct {
	Format int `json:"format"`
	Blocks map[string]struct {
		Summary struct {
			Types []verify.NamedType `json:"types"`
		} `json:"summary"`
	} `json:"blocks"`
}

type ModelModule struct {
	Module    string   `json:"module"`
	Path      string   `json:"path"`
	Text      string   `json:"text"`
	Functions []string `json:"functions,omitempty"`
}

type TranslatedFunction struct {
	ID           string       `json:"id"`
	Model        string       `json:"model"`
	Dependencies []string     `json:"dependencies"`
	Error        *SourceError `json:"error,omitempty"`
}

type Translation struct {
	Format     int                  `json:"format"`
	Modules    []ModelModule        `json:"modules"`
	Aggregates []ModelModule        `json:"aggregates"`
	Functions  []TranslatedFunction `json:"functions"`
}

func isGenerated(data []byte) bool {
	return bytes.HasPrefix(data, []byte("// Code generated by leanfran-go "))
}

func readRegular(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("expected a regular file: %s", path)
	}
	return os.ReadFile(path)
}

func belongsTo(data []byte, module string) bool {
	return embeddedHeader.Match(data) &&
		bytes.Contains(bytes.SplitN(data, []byte("\n"), 2)[0], []byte(" from "+module+". "))
}

func (p *project) relative(path string) string {
	rel, err := filepath.Rel(p.root, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}

func load(root string, versions Versions) (*project, []*block, []*verify.Function, error) {
	p, err := loadProject(root, versions)
	if err != nil {
		return nil, nil, nil, err
	}
	if err := p.scan(); err != nil {
		return nil, nil, nil, err
	}
	if err := p.loadModels(); err != nil {
		return nil, nil, nil, err
	}
	blocks, err := p.order()
	if err != nil {
		return nil, nil, nil, err
	}
	return p, blocks, p.functions(), nil
}

func (p *project) prelude(b *block, models *strings.Builder, emitted map[string]bool) (string, batchJob) {
	var header strings.Builder
	imports := slices.Clone(b.imports)
	for _, use := range b.uses {
		imports = append(imports, p.blocks[use].module)
	}
	job := batchJob{Module: b.module, Package: b.pkg.name, GoPath: b.pkg.path}
	job.Models = slices.Clone(b.models)
	for _, dep := range b.deps {
		job.TypeModules = append(job.TypeModules, dep.module+"="+dep.pkg.path)
		for _, m := range dep.models {
			if !slices.Contains(job.Models, m) {
				job.Models = append(job.Models, m)
			}
		}
	}
	if len(job.Models) > 0 {
		imports = append(imports, "LeanGoModels")
	}
	for _, name := range imports {
		fmt.Fprintf(&header, "import %s\n", name)
	}
	fmt.Fprintf(&header, "set_option warningAsError true\n\nnamespace %s\n", b.module)
	for _, use := range b.uses {
		fmt.Fprintf(&header, "open %s\n", p.blocks[use].module)
	}
	plainNames := make(map[string]int)
	for _, m := range b.models {
		if m.Plain {
			plainNames[m.Name]++
		}
	}
	for _, m := range b.models {
		namespace, name, _ := strings.Cut(m.Lean, ".")
		prefix, _, _ := strings.Cut(name, ".")
		if !m.Plain {
			fmt.Fprintf(&header, "open %s.%s (%s)\n", namespace, prefix, leanIdent(strings.TrimPrefix(name, prefix+".")))
		} else if plainNames[m.Name] == 1 {
			fmt.Fprintf(&header, "namespace GoValues\nabbrev %s := %s.%s.%s\nend GoValues\n",
				leanIdent(m.Name), namespace, prefix, leanIdent(m.Name))
		}
		if !emitted[m.Lean] {
			models.WriteString(m.Source)
			emitted[m.Lean] = true
		}
	}
	header.WriteString("\n")
	return header.String(), job
}

func (p *project) testable(models []*verify.Function) map[string]bool {
	pkgs := make(map[string]bool)
	for _, m := range models {
		if m.Err == nil && p.blocks[m.Spec] != nil {
			pkgs[m.Package] = true
		}
	}
	return pkgs
}

func (p *project) stray(models []*verify.Function) ([]string, error) {
	current := make(map[string]bool)
	for _, b := range p.blocks {
		current[b.pkg.dir] = true
	}
	tested := p.testable(models)
	var stray []string
	for _, dir := range p.dirs {
		name, err := p.packagePath(dir)
		if err != nil {
			return nil, err
		}
		if !current[dir] {
			for _, file := range generatedNames {
				path := filepath.Join(dir, file)
				if data, err := readRegular(path); err == nil && belongsTo(data, moduleName(name)) {
					stray = append(stray, p.relative(path))
				}
			}
		}
		path := filepath.Join(dir, manifestName)
		var m struct {
			Block string   `json:"block"`
			Hash  string   `json:"hash"`
			Files []string `json:"files"`
		}
		if data, err := readRegular(path); err == nil && json.Unmarshal(data, &m) == nil && m.Block == name &&
			m.Hash != "" && slices.Equal(m.Files, generatedNames) {
			stray = append(stray, p.relative(path))
		}
		path = filepath.Join(dir, verify.TestFile)
		if data, err := readRegular(path); err == nil && !tested[name] && bytes.HasPrefix(data, []byte(modelTestHeader)) {
			stray = append(stray, p.relative(path))
		}
	}
	slices.Sort(stray)
	return stray, nil
}

func (p *project) origin(file string, line, column int) Origin {
	return Origin{File: p.relative(file), Line: line, Column: column}
}

func functionHash(m *verify.Function) (string, error) {
	var buf bytes.Buffer
	if m.Decl.Doc != nil {
		for _, c := range m.Decl.Doc.List {
			buf.WriteString(c.Text + "\n")
		}
	}
	decl := *m.Decl
	decl.Doc = nil
	if err := format.Node(&buf, m.Files, &decl); err != nil {
		return "", err
	}
	sum := sha256.Sum256(buf.Bytes())
	return hex.EncodeToString(sum[:]), nil
}

func functionID(m *verify.Function) string {
	return m.Package + "." + m.Decl.Name.Name
}

func labels(m *verify.Function) []string {
	if len(m.Checks) == 0 {
		return []string{"model"}
	}
	var result []string
	for _, pred := range m.Checks {
		result = append(result, pred.Label)
	}
	return result
}

func Scan(root string, versions Versions) (*ScanResult, error) {
	p, blocks, models, err := load(root, versions)
	if err != nil {
		return nil, err
	}
	result := &ScanResult{
		Format: 1, Scope: []string{"."}, Require: p.config.Require, Blocks: []Block{},
		Files: []WorkspaceFile{}, Functions: []Function{},
	}
	if result.Require == nil {
		result.Require = []map[string]any{}
	}
	var aggregate, modelSource strings.Builder
	modelSource.WriteString("set_option warningAsError true\n")
	emitted := make(map[string]bool)
	for _, b := range blocks {
		prelude, job := p.prelude(b, &modelSource, emitted)
		origin := p.origin(b.pos.Filename, b.pos.Line, b.pos.Column)
		if b.source.offsets == nil {
			origin = p.origin(b.source.file, 1, 1)
		}
		uses := b.uses
		if uses == nil {
			uses = []string{}
		}
		result.Blocks = append(result.Blocks, Block{
			Name: b.pkg.path, Module: b.module, Path: strings.ReplaceAll(b.module, ".", "/") + ".lean",
			Prelude: prelude, Text: b.source.text, Postlude: "\n\nend " + b.module + "\n", Map: b.source.entries(),
			Origin: origin, Uses: uses, Hash: b.hash, Job: job,
			Output: map[string]string{"dir": p.relative(b.pkg.dir)},
		})
		fmt.Fprintf(&aggregate, "import %s\n", b.module)
	}
	result.Workspace = []WorkspaceFile{
		{Path: "LeanGoEmbed.lean", Text: aggregate.String()},
		{Path: "LeanGoModels.lean", Text: modelSource.String()},
	}
	if result.Stray, err = p.stray(models); err != nil {
		return nil, err
	}
	if result.Stray == nil {
		result.Stray = []string{}
	}
	for _, m := range models {
		hash, err := functionHash(m)
		if err != nil {
			return nil, err
		}
		pos := m.Files.Position(m.Decl.Pos())
		pkg := p.packages[m.Package]
		data := FunctionData{
			Dir: p.relative(pkg.dir), Package: pkg.name, Function: m.Decl.Name.Name, Spec: m.Spec,
			Requires: m.Needs, Checks: [][2]string{},
		}
		for _, pred := range m.Checks {
			data.Checks = append(data.Checks, [2]string{pred.Label, pred.Name})
		}
		if m.Err != nil {
			data.Error = m.Err.Error()
		}
		result.Functions = append(result.Functions, Function{
			ID: functionID(m), Labels: labels(m), Hash: hash,
			Origin: p.origin(pos.Filename, pos.Line, pos.Column), Data: data,
		})
	}
	if result.ProofInputs, err = p.proofInputs(); err != nil {
		return nil, err
	}
	return result, nil
}

func (p *project) sourceError(m *verify.Function, err error) *SourceError {
	match := located.FindStringSubmatch(err.Error())
	if match == nil {
		pos := m.Files.Position(m.Decl.Pos())
		return &SourceError{File: p.relative(pos.Filename), Line: pos.Line, Column: pos.Column, Message: err.Error()}
	}
	line, _ := strconv.Atoi(match[2])
	column, _ := strconv.Atoi(match[3])
	return &SourceError{File: p.relative(match[1]), Line: line, Column: column, Message: match[4]}
}

func Translate(root string, versions Versions, input TranslateInput) (*Translation, error) {
	p, _, models, err := load(root, versions)
	if err != nil {
		return nil, err
	}
	for _, name := range sortedKeys(p.blocks) {
		b := p.blocks[name]
		b.verifyTypes = input.Blocks[name].Summary.Types
		for j := range b.verifyTypes {
			b.verifyTypes[j].Module = b.module
		}
	}
	if len(models) > 0 {
		if err := p.typeModels(models); err != nil {
			return nil, err
		}
	}
	defs := verify.Definitions(models)
	ids := make(map[string]string)
	for _, d := range defs {
		ids[d.Module()] = functionID(d.Model)
	}
	result := &Translation{Format: 1, Modules: []ModelModule{}, Aggregates: []ModelModule{}, Functions: []TranslatedFunction{}}
	packages := make(map[string][]string)
	for _, d := range defs {
		model := d.Model
		f := TranslatedFunction{ID: functionID(model), Model: model.Name(), Dependencies: []string{}}
		if d.Err != nil {
			f.Error = p.sourceError(model, d.Err)
			result.Functions = append(result.Functions, f)
			continue
		}
		imports := append([]string{"LeanGoLib.Go", moduleName(model.Spec)}, d.TypeImports...)
		for _, mod := range d.Imports {
			imports = append(imports, mod)
			f.Dependencies = append(f.Dependencies, ids[mod])
		}
		var source strings.Builder
		for _, mod := range imports {
			fmt.Fprintf(&source, "import %s\n", mod)
		}
		source.WriteString("\n" + d.Source)
		result.Modules = append(result.Modules, ModelModule{
			Module: d.Module(), Path: "verification/" + strings.ReplaceAll(d.Module(), ".", "/") + ".lean",
			Text: source.String(), Functions: []string{f.ID},
		})
		pkg := verify.ModelModule(model.Package)
		packages[pkg] = append(packages[pkg], d.Module())
		result.Functions = append(result.Functions, f)
	}
	for _, pkg := range sortedKeys(packages) {
		result.Aggregates = append(result.Aggregates, ModelModule{
			Module: pkg, Path: "verification/" + strings.ReplaceAll(pkg, ".", "/") + ".lean",
			Text: "import " + strings.Join(packages[pkg], "\nimport ") + "\n",
		})
	}
	return result, nil
}
