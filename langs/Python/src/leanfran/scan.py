"""``scan``: the Lean blocks, models and ``@model`` functions of a package, for ``leanfran --lang python``.

The package is imported in the recording state: ``lean(...)`` records its block and returns a
placeholder, so no generated module is imported and no ``sync`` starts. Nothing is written to the
project.
"""

import ast
import hashlib
import importlib
import inspect
import io
import json
import pathlib
import sys
import textwrap
import tokenize
import traceback
import typing
import warnings

from leanfran import embed, models, translate, verify

GENERATED_HEADER = "# Generated by leanfran-python "
INIT_TEXT = '"""Python modules generated by `leanfran sync`. Do not edit."""\n'


class ScanError(Exception):
    def __init__(self, message, code=254):
        super().__init__(message)
        self.code = code


def relative(root, path):
    return pathlib.Path(path).resolve().relative_to(root).as_posix()


def package_modules(pkg_dir):
    """The dotted names of the modules of the package, outside ``_lean/``."""
    names = []
    for path in sorted(pkg_dir.rglob("*.py")):
        rel = path.relative_to(pkg_dir)
        if rel.parts[0] == "_lean" or "__pycache__" in rel.parts or rel.name == "__main__.py":
            continue
        parts = [pkg_dir.name, *rel.with_suffix("").parts]
        if parts[-1] == "__init__":
            parts = parts[:-1]
        names.append((".".join(parts), path))
    return names


def import_error(root, pkg_dir, module_path, error):
    """``<file>:<line>: <exception type>: <message>`` of an exception raised by importing a module."""
    file, line = module_path, 1
    if isinstance(error, SyntaxError) and error.filename:
        file, line = error.filename, error.lineno or 1
    else:
        for frame in traceback.extract_tb(error.__traceback__):
            p = pathlib.Path(frame.filename)
            if p.is_absolute() and p.resolve().is_relative_to(pkg_dir):
                file, line = frame.filename, frame.lineno
    try:
        shown = relative(root, file)
    except ValueError:
        shown = str(file)
    return f"{shown}:{line}: {type(error).__name__}: {error}"


def import_package(root, pkg_dir):
    sys.path.insert(0, str(pkg_dir.parent))
    for name, path in package_modules(pkg_dir):
        try:
            importlib.import_module(name)
        except Exception as e:  # noqa: BLE001
            raise ScanError(import_error(root, pkg_dir, path, e)) from None


def record_blocks(root, pkg_dir):
    """Imports every module of the package and returns the blocks their `lean(...)` calls define."""
    sys.dont_write_bytecode = True
    embed._recording = []
    try:
        import_package(root, pkg_dir)
        return list(embed._recording)
    finally:
        embed._recording = None


def resolve_use(block, use, by_name):
    q = use if ":" in use else f"{block.module}:{use}"
    b = by_name.get(q)
    if b is None:
        raise ScanError(f"{block.file}:{block.line}: lean block {block.name!r} uses unknown block {use!r}")
    return b


def block_head(block, by_name):
    imports = list(block.imports)
    opens = []
    if block.models:
        for module in models.modules_source(list(block.models)):
            ns = models.dotted(models.models_namespace(module))
            imports.append(ns)
            opens.append(ns)
    for use in block.uses:
        other = resolve_use(block, use, by_name)
        ns = models.dotted(other.lean_module)
        imports.append(ns)
        opens.append(ns)
    ns = models.dotted(block.lean_module)
    head = "".join(f"import {i}\n" for i in dict.fromkeys(imports))
    head += f"\nnamespace {ns}\n"
    head += "".join(f"open {o}\n" for o in opens)
    head += "\n"
    return head, f"\n\nend {ns}\n"


def _char_column(line, byte_offset):
    return len(line.encode()[:byte_offset].decode(errors="replace")) + 1


def _literal_call(tree, block):
    """The innermost call on the block's line whose string argument is the block's source."""
    best = None
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not node.lineno <= block.line <= (node.end_lineno or node.lineno):
            continue
        for a in [*node.args, *(k.value for k in node.keywords if k.arg == "source")]:
            later = best is None or (node.lineno, node.col_offset) >= (best[0].lineno, best[0].col_offset)
            if isinstance(a, ast.Constant) and a.value == block.source and later:
                best = (node, a)
    return best


def _string_tokens(text, literal):
    start = (literal.lineno, literal.col_offset)
    end = (literal.end_lineno, literal.end_col_offset)
    lines = text.splitlines(keepends=True)
    found = []
    for tok in tokenize.generate_tokens(io.StringIO(text).readline):
        if tok.type != tokenize.STRING:
            continue
        line = lines[tok.start[0] - 1]
        pos = (tok.start[0], len(line[: tok.start[1]].encode()))
        if start <= pos < end:
            found.append(tok)
    return found


def _escape_length(body, i):
    """The length of the escape sequence starting at ``body[i] == "\\\\"``."""
    c = body[i + 1] if i + 1 < len(body) else ""
    if c == "x":
        return 4
    if c == "u":
        return 6
    if c == "U":
        return 10
    if c == "N":
        close = body.find("}", i)
        return close - i + 1 if close >= 0 else 2
    if c in "01234567":
        n = 2
        while n < 4 and i + n < len(body) and body[i + n] in "01234567":
            n += 1
        return n
    return 2


def _unescape(seq):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return ast.literal_eval(f'"{seq}"')


def _token_entries(tok, value_offset, entries):
    """Adds the map entries of one string token; returns the UTF-8 length of its value."""
    text = tok.string
    q = 0
    while text[q] not in "'\"":
        q += 1
    raw = "r" in text[:q].lower()
    quote = text[q : q + 3] if text[q : q + 3] in ('"""', "'''") else text[q]
    body = text[q + len(quote) : len(text) - len(quote)]
    line, column = tok.start[0], tok.start[1] + q + len(quote) + 1
    offset = value_offset
    start = True
    i = 0
    while i < len(body):
        if start:
            entries.append([offset, line, column])
            start = False
        c = body[i]
        if c == "\\" and not raw:
            n = _escape_length(body, i)
            seq = body[i : i + n]
            value = "" if seq.startswith("\\\n") else _unescape(seq)
            offset += len(value.encode())
            for ch in seq:
                if ch == "\n":
                    line, column = line + 1, 1
                else:
                    column += 1
            start = True
            i += n
            continue
        offset += len(c.encode())
        if c == "\n":
            line, column = line + 1, 1
            start = True
        else:
            column += 1
        i += 1
    return offset - value_offset


def source_map(root, block):
    """The origin of the block's call and the map from its source's byte offsets to the Python file."""
    file = relative(root, block.file)
    fallback_origin = {"file": file, "line": block.line, "column": 1}
    try:
        text = pathlib.Path(block.file).read_text()
        tree = ast.parse(text)
    except (OSError, SyntaxError, ValueError):
        return fallback_origin, _line_map(block.source, block.line, 1)
    found = _literal_call(tree, block)
    if found is None:
        return fallback_origin, _line_map(block.source, block.line, 1)
    call, literal = found
    lines = text.splitlines()
    origin = {"file": file, "line": call.lineno, "column": _char_column(lines[call.lineno - 1], call.col_offset)}
    entries = []
    offset = 0
    try:
        for tok in _string_tokens(text, literal):
            offset += _token_entries(tok, offset, entries)
    except (SyntaxError, ValueError, IndexError):
        return origin, _line_map(block.source, origin["line"], origin["column"])
    if offset != len(block.source.encode()) or not entries:
        return origin, _line_map(block.source, origin["line"], origin["column"])
    return origin, entries


def _line_map(source, line, column):
    entries = [[0, line, column]]
    offset = 0
    for part in source.split("\n")[:-1]:
        offset += len(part.encode()) + 1
        entries.append([offset, line, column])
    return entries


def function_labels(spec, hints):
    """The labels of the obligations of a ``@model`` function (``scan`` and ``translate`` agree)."""
    labels = []
    if spec.refines is not None:
        labels.append("refines")
    labels.extend(spec.ensures)
    if translate.is_nat(hints.get("return")):
        labels.append("returns_nat")
    return labels


def source_hash(fn):
    src = textwrap.dedent(inspect.getsource(fn))
    return hashlib.sha256(ast.dump(ast.parse(src)).encode()).hexdigest()


def hints_of(fn):
    try:
        return typing.get_type_hints(fn, include_extras=True)
    except Exception:  # noqa: BLE001
        return {}


def collect_models(ann, acc):
    from pydantic import BaseModel

    while typing.get_origin(ann) is typing.Annotated:
        ann = typing.get_args(ann)[0]
    if isinstance(ann, type) and issubclass(ann, BaseModel):
        acc.add(ann)
        return
    for a in typing.get_args(ann):
        collect_models(a, acc)


def model_specs(pkg_dir):
    return [s for s in verify.REGISTRY if pathlib.Path(s.fn.__code__.co_filename).resolve().is_relative_to(pkg_dir)]


def translator_sources():
    here = pathlib.Path(__file__).parent
    return {name: hashlib.sha256((here / name).read_bytes()).hexdigest() for name in TRANSLATOR_SOURCES}


TRANSLATOR_SOURCES = ("models.py", "translate.py", "translation.py")


def scan(root, pkg_dir):
    root = pathlib.Path(root).resolve()
    pkg_dir = pathlib.Path(pkg_dir).resolve()
    pkg = relative(root, pkg_dir)
    verify.REGISTRY.clear()
    blocks = record_blocks(root, pkg_dir)
    by_name = {}
    for b in blocks:
        if b.qualname in by_name:
            raise ScanError(f"{relative(root, b.file)}:{b.line}: lean block {b.name!r} is defined twice in {b.module}")
        by_name[b.qualname] = b

    model_modules = {}
    for b in blocks:
        if b.models:
            model_modules.update(models.modules_source(list(b.models)))
    specs = model_specs(pkg_dir)
    function_models = set()
    for s in specs:
        for ann in hints_of(s.fn).values():
            collect_models(ann, function_models)
    if function_models:
        for module, src in models.modules_source(list(function_models)).items():
            model_modules.setdefault(module, src)

    out_blocks = []
    registry = {}
    for b in blocks:
        prelude, postlude = block_head(b, by_name)
        origin, entries = source_map(root, b)
        type_modules = [
            {"namespace": ".".join(models.models_namespace(m)), "module": m, "adopt": True}
            for m in (models.modules_source(list(b.models)) if b.models else {})
        ]
        uses = []
        for use in b.uses:
            other = resolve_use(b, use, by_name)
            uses.append(other.qualname)
            type_modules.append(
                {"namespace": ".".join(other.lean_module), "module": f"{other.top_package}._lean.{other.stem}"}
            )
        module = ".".join(b.lean_module)
        key = embed.block_key(b)
        registry[b.qualname] = key
        out_blocks.append(
            {
                "name": b.qualname,
                "module": module,
                "path": pathlib.PurePosixPath(*b.lean_module).with_suffix(".lean").as_posix(),
                "prelude": prelude,
                "text": b.source,
                "postlude": postlude,
                "map": entries,
                "origin": origin,
                "uses": uses,
                "hash": key,
                "job": {"module": module, "namespace": module, "type_modules": type_modules},
                "output": {"file": f"{pkg}/_lean/{b.stem}.py"},
            }
        )

    workspace = [
        {"path": pathlib.PurePosixPath(*models.models_namespace(m)).with_suffix(".lean").as_posix(), "text": src}
        for m, src in model_modules.items()
    ]
    workspace.append(
        {
            "path": "LeanPythonEmbed.lean",
            "text": "".join(f"import {models.dotted(b.lean_module)}\n" for b in blocks) or "\n",
        }
    )
    workspace.append(
        {
            "path": "LeanPythonModels.lean",
            "text": "".join(f"import {models.dotted(models.models_namespace(m))}\n" for m in model_modules) or "\n",
        }
    )

    files = [
        {"path": f"{pkg}/_lean/__init__.py", "text": INIT_TEXT},
        {"path": f"{pkg}/_lean/blocks.json", "text": json.dumps(registry, indent=2, sort_keys=True) + "\n"},
    ]

    stray = []
    lean_dir = pkg_dir / "_lean"
    if lean_dir.is_dir():
        for path in sorted(lean_dir.iterdir()):
            if not path.is_file() or path.is_symlink():
                continue
            if path.name in ("__init__.py", "blocks.json"):
                stray.append(relative(root, path))
                continue
            try:
                with path.open("rb") as f:
                    first = f.readline()
            except OSError:
                continue
            if first.startswith(GENERATED_HEADER.encode()):
                stray.append(relative(root, path))

    functions = []
    for s in specs:
        fn = s.fn
        functions.append(
            {
                "id": s.qualname,
                "labels": function_labels(s, hints_of(fn)),
                "hash": source_hash(fn),
                "origin": {
                    "file": relative(root, fn.__code__.co_filename),
                    "line": fn.__code__.co_firstlineno,
                    "column": 1,
                },
                "data": {},
            }
        )

    proof_inputs = hashlib.sha256(
        json.dumps({"blocks": registry, "translator": translator_sources()}, sort_keys=True).encode()
    ).hexdigest()

    return {
        "format": 1,
        "scope": [pkg],
        "require": [],
        "inputs": "",
        "blocks": out_blocks,
        "workspace": workspace,
        "files": files,
        "stray": stray,
        "functions": functions,
        "proof_inputs": proof_inputs,
    }
